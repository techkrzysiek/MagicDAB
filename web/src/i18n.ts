const dicts = { en, pl }

export function useT() {
  const lang = useStore((s) => s.lang)
  const d = dicts[lang] || en
  return (k: Key | string) => (d as Record<string, string>)[k] ?? (en as Record<string, string>)[k] ?? k
}

export function tr(k: string) {
  const d = dicts[useStore.getState().lang] || en
  return (d as Record<string, string>)[k] ?? (en as Record<string, string>)[k] ?? k
}

