#!/usr/bin/env python3
"""Generates the names of the TV-Anytime content genres (ContentCS) for the
receiver (crates/dab/src/genres.rs) and the interface (web/src/genres.ts).

    curl -O https://raw.githubusercontent.com/paulhiggs/dvb-i-tools/main/res/tva/ContentCS.xml
    python3 build/genres.py ContentCS.xml
"""
import os
import sys
import xml.etree.ElementTree as ET

LANG = '{http://www.w3.org/XML/1998/namespace}lang'


def nice(name):
    name = ' '.join(name.split())
    # the top levels are in capitals
    if name.upper() == name and any(c.isalpha() for c in name):
        name = name[0] + name[1:].lower()
    if name.count('(') > name.count(')'):
        name += ')'
    return name


def main():
    root = ET.parse(sys.argv[1]).getroot()
    names = {}

    def walk(e):
        for term in e.findall('Term'):
            en = [n.text for n in term.findall('Name') if n.get(LANG, 'en') == 'en' and n.text]
            if en:
                names[term.get('termID')] = nice(en[0])
            walk(term)

    walk(root)
    codes = sorted(names)
    here = os.path.dirname(os.path.abspath(__file__))
    q = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    with open(os.path.join(here, '..', 'crates', 'dab', 'src', 'genres_table.rs'), 'w') as f:
        f.write('// Generated by build/genres.py from %s: do not edit.\n' % root.get('uri'))
        f.write('pub(crate) static CONTENT: &[(&str, &str)] = &[\n')
        for c in codes:
            f.write('    (%s, %s),\n' % (q(c), q(names[c])))
        f.write('];\n')
    with open(os.path.join(here, '..', 'web', 'src', 'genres_table.ts'), 'w') as f:
        f.write('// Generated by build/genres.py from %s: do not edit.\n' % root.get('uri'))
        f.write('export const CONTENT: Record<string, string> = {\n')
        for c in codes:
            f.write('  %s: %s,\n' % (q(c), q(names[c])))
        f.write('}\n')
    print(len(codes), 'genres')


main()
